# Geri sayımı 5 değerinden başlatır.
sayac = 5

# Sayaç 1 veya daha büyük olduğu sürece döngüyü sürdürür.
while sayac >= 1:
    # O anki geri sayım değerini ekrana yazdırır.
    print(sayac)
    # Sayaç değerini bir azaltır.
    sayac -= 1

# Geri sayım tamamlandığında mesaj gösterir.
print("Başla!")
