# Sayacı 1 değerinden başlatır.
sayac = 1

# Sayaç 10'dan küçük olduğu sürece döngüyü sürdürür.
while sayac < 10:
    # O anki sayaç değerini ekrana yazdırır.
    print(sayac)
    # Sayacı üçer üçer artırır.
    sayac += 3

# Döngü sonunda sayacın ulaştığı değeri gösterir.
print("Döngü sonundaki değer:", sayac)
