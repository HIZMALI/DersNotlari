# Sayacı 1 değerinden başlatır.
sayac = 1

# Sayaç 5 veya daha küçük olduğu sürece döngüyü sürdürür.
while sayac <= 5:
    # O anki sayaç değerini ekrana yazdırır.
    print("Tur:", sayac)
    # Sayaç değerini bir artırarak bir sonraki tura hazırlar.
    sayac += 1

# Döngü sona erdikten sonra tamamlanma mesajını gösterir.
print("Döngü tamamlandı.")
