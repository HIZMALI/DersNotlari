# Dört şehirden oluşan bir liste oluşturur.
sehirler = ["Ankara", "İstanbul", "İzmir", "Bursa"]

# İlk elemanı pozitif indeks kullanarak ekrana yazdırır.
print("İlk şehir:", sehirler[0])

# Üçüncü elemanı pozitif indeks kullanarak ekrana yazdırır.
print("Üçüncü şehir:", sehirler[2])

# Son elemanı negatif indeks kullanarak ekrana yazdırır.
print("Son şehir:", sehirler[-1])

# Sondan ikinci elemanı negatif indeks kullanarak ekrana yazdırır.
print("Sondan ikinci şehir:", sehirler[-2])
