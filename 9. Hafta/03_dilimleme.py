# Beş harften oluşan bir liste oluşturur.
harfler = ["A", "B", "C", "D", "E"]

# İndeks 1'den başlayıp indeks 4'e gelmeden önceki elemanları alır.
print("1:4 dilimi:", harfler[1:4])

# Listenin ilk üç elemanını alır.
print("İlk üç:", harfler[:3])

# Listenin son üç elemanını alır.
print("Son üç:", harfler[-3:])

# Listenin ters çevrilmiş kopyasını üretir.
print("Ters sıra:", harfler[::-1])
