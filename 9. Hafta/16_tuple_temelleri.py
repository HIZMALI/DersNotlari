# Enlem ve boylam değerlerini tuple içinde birlikte saklar.
koordinat = (41.01, 28.97)

# Tuple'ın tamamını ekrana yazdırır.
print("Koordinat:", koordinat)

# İlk eleman olan enlem değerini ekrana yazdırır.
print("Enlem:", koordinat[0])

# İkinci eleman olan boylam değerini ekrana yazdırır.
print("Boylam:", koordinat[1])

# Veri tipinin tuple olduğunu ekrana yazdırır.
print("Veri tipi:", type(koordinat))
