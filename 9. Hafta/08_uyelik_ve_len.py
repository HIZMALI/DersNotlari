# Aktif kullanıcı adlarını içeren bir liste oluşturur.
kullanicilar = ["ayse", "mert", "selin"]

# Listedeki toplam kullanıcı sayısını ekrana yazdırır.
print("Kullanıcı sayısı:", len(kullanicilar))

# ayse değerinin listede bulunup bulunmadığını kontrol eder.
print("ayse listede mi?", "ayse" in kullanicilar)

# can değerinin listede bulunmadığını kontrol eder.
print("can listede değil mi?", "can" not in kullanicilar)
