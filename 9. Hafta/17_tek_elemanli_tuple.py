# Parantez içindeki tek sayıyı virgülsüz yazar; bu nedenle değer int olur.
tuple_degil = (5)

# Tek elemanın ardından virgül koyarak gerçek tuple oluşturur.
gercek_tuple = (5,)

# İlk değişkenin veri tipini ekrana yazdırır.
print(type(tuple_degil))

# İkinci değişkenin veri tipini ekrana yazdırır.
print(type(gercek_tuple))
