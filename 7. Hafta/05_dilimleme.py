# Dilimleme örneklerinde kullanılacak metni oluşturur.
metin = "Programlama"

# İlk dört karakteri alır; 4 indeksi sonuca dahil değildir.
print(metin[0:4])

# 4 indeksinden başlayıp 8 indeksine gelmeden önceki karakterleri alır.
print(metin[4:8])

# Metnin başlangıcından 5 indeksine kadar olan kısmı alır.
print(metin[:5])

# 5 indeksinden metnin sonuna kadar olan kısmı alır.
print(metin[5:])
