# Büyük ve küçük harflerin karışık olduğu bir metin oluşturur.
metin = "PyThOn Programlama"

# Metnin tamamını büyük harfe dönüştürülmüş yeni bir değer olarak yazdırır.
print(metin.upper())

# Metnin tamamını küçük harfe dönüştürülmüş yeni bir değer olarak yazdırır.
print(metin.lower())

# Orijinal stringin değişmediğini göstermek için metni tekrar yazdırır.
print(metin)
