sayi_1 = 17  # İlk tam sayı değerini tanımlar.
sayi_2 = 5  # İkinci tam sayı değerini tanımlar.
toplam = sayi_1 + sayi_2  # İki sayıyı toplar.
fark = sayi_1 - sayi_2  # İkinci sayıyı ilk sayıdan çıkarır.
carpim = sayi_1 * sayi_2  # İki sayıyı çarpar.
normal_bolme = sayi_1 / sayi_2  # Normal bölme yapar ve ondalıklı sonucu üretir.
tam_bolme = sayi_1 // sayi_2  # Bölümün tam kısmını bulur.
kalan = sayi_1 % sayi_2  # Bölme işleminden kalan değeri bulur.
us = sayi_1 ** 2  # İlk sayının karesini hesaplar.
print(f"Toplam: {toplam}")  # Toplama sonucunu ekrana yazar.
print(f"Fark: {fark}")  # Çıkarma sonucunu ekrana yazar.
print(f"Çarpım: {carpim}")  # Çarpma sonucunu ekrana yazar.
print(f"Normal bölme: {normal_bolme}")  # Normal bölme sonucunu ekrana yazar.
print(f"Tam bölme: {tam_bolme}")  # Tam bölme sonucunu ekrana yazar.
print(f"Kalan: {kalan}")  # Kalan sonucunu ekrana yazar.
print(f"17'nin karesi: {us}")  # Üs alma sonucunu ekrana yazar.
